#!/usr/bin/env node
// Fails if any installed dependency (prod or dev) has a licence that isn't permissive / Apache-2.0
// compatible. With --notices, also writes THIRD_PARTY_NOTICES.md for everything shipped to users.
import checker from 'license-checker';
import { readFileSync, writeFileSync, existsSync } from 'node:fs';

const ALLOWED = new Set([
  'MIT',
  'MIT-0',
  'ISC',
  'BSD-2-Clause',
  'BSD-3-Clause',
  '0BSD',
  'Apache-2.0',
  'OFL-1.1',
  'CC0-1.0',
  'CC-BY-3.0', // data-only packages (e.g. spdx lists) used by build tooling
  'CC-BY-4.0', // caniuse-lite browser data used by build tooling
  'BlueOak-1.0.0',
  'Python-2.0',
  'Unlicense',
  'Zlib',
]);
const BANNED = /\b(A?GPL|LGPL|SSPL|EUPL|MPL|CC-BY-NC|CC-BY-SA|Commons Clause|BUSL|Elastic|UNLICENSED|UNKNOWN)\b/i;

function allowed(expr) {
  const e = String(expr).replace(/\*$/, '').trim();
  if (BANNED.test(e) && !/\bOR\b/.test(e)) return false;
  const clean = e.replace(/[()]/g, '');
  if (/\bOR\b/.test(clean)) return clean.split(/\s+OR\s+/).some((p) => allowed(p));
  if (/\bAND\b/.test(clean)) return clean.split(/\s+AND\s+/).every((p) => allowed(p));
  return ALLOWED.has(clean);
}

function scan(production) {
  return new Promise((resolve, reject) =>
    checker.init({ start: process.cwd(), production, excludePrivatePackages: true }, (err, pkgs) =>
      err ? reject(err) : resolve(pkgs),
    ),
  );
}

const all = await scan(false);
const bad = Object.entries(all).filter(([, info]) => {
  const lic = Array.isArray(info.licenses) ? info.licenses.join(' AND ') : info.licenses;
  return !allowed(lic);
});

const counts = {};
for (const info of Object.values(all)) {
  const lic = Array.isArray(info.licenses) ? info.licenses.join(' AND ') : String(info.licenses);
  counts[lic] = (counts[lic] ?? 0) + 1;
}
console.log(`Checked ${Object.keys(all).length} packages:`);
for (const [l, n] of Object.entries(counts).sort((a, b) => b[1] - a[1])) console.log(`  ${String(n).padStart(4)}  ${l}`);

if (bad.length) {
  console.error('\n✖ Incompatible or unknown licences:');
  for (const [name, info] of bad) console.error(`  ${name}: ${info.licenses}`);
  process.exit(1);
}
console.log('\n✔ All dependency licences are compatible with Apache-2.0.');

if (process.argv.includes('--notices')) {
  const prod = await scan(true);
  const self = JSON.parse(readFileSync('package.json', 'utf8')).name;
  const lines = [
    '# Third-party notices',
    '',
    'OpenGaze is licensed under Apache-2.0. It ships or loads the following third-party components.',
    'Generated by `npm run notices` (license-checker). Development-only tools are checked by',
    '`npm run license-check` but are not redistributed and are not listed here.',
    '',
    '## Bundled assets',
    '',
    '| Component | Licence | Source |',
    '|---|---|---|',
    '| MediaPipe Face Landmarker model (`public/models/face_landmarker.task`) | Apache-2.0 | https://ai.google.dev/edge/mediapipe/solutions/vision/face_landmarker |',
    '| MediaPipe Tasks Vision WASM runtime (`public/wasm`, copied from `@mediapipe/tasks-vision`) | Apache-2.0 | https://github.com/google-ai-edge/mediapipe |',
    '| Atkinson Hyperlegible font (via `@fontsource/atkinson-hyperlegible`) | OFL-1.1 | https://www.brailleinstitute.org/freefont |',
    '| Text-entry phrases (5 phrases, Measure benchmark) | Published research phrase set | MacKenzie & Soukoreff (2003), CHI EA |',
    '',
    '## npm packages shipped in the app or proxy',
    '',
    '| Package | Version | Licence | Repository |',
    '|---|---|---|---|',
  ];
  const texts = [];
  for (const [id, info] of Object.entries(prod).sort()) {
    const at = id.lastIndexOf('@');
    const name = id.slice(0, at);
    const version = id.slice(at + 1);
    if (name === self) continue;
    lines.push(`| ${name} | ${version} | ${info.licenses} | ${info.repository ?? ''} |`);
    if (info.licenseFile && existsSync(info.licenseFile) && !/readme/i.test(info.licenseFile)) {
      texts.push(`### ${name}@${version}\n\n\`\`\`\n${readFileSync(info.licenseFile, 'utf8').trim()}\n\`\`\`\n`);
    }
  }
  lines.push('', '## Licence texts', '', ...texts);
  writeFileSync('THIRD_PARTY_NOTICES.md', lines.join('\n') + '\n');
  console.log(`Wrote THIRD_PARTY_NOTICES.md (${Object.keys(prod).length - 1} packages).`);
}
